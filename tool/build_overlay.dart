// Compiles the overlay program to JavaScript and embeds it in the package.
//
//   dart run tool/build_overlay.dart          rebuild lib/src/server/overlay_bundle.g.dart
//   dart run tool/build_overlay.dart --check  fail if the bundle is older than its sources
//
// The bundle is checked in, so apps that depend on the package need no build
// step of their own.
import 'dart:convert';
import 'dart:io';

const String _entry = 'lib/src/overlay/main.dart';
const String _output = 'lib/src/server/overlay_bundle.g.dart';
const List<String> _sources = ['lib/src/overlay', 'lib/src/core', 'lib/src/protocol.dart'];

Future<void> main(List<String> arguments) async {
  final hash = _hashSources();

  if (arguments.contains('--check')) {
    final current = RegExp("overlayBundleHash = '([0-9a-f]*)'").firstMatch(File(_output).readAsStringSync())?.group(1);
    if (current != hash) {
      stderr.writeln('The overlay bundle is out of date. Run: dart run tool/build_overlay.dart');
      exitCode = 1;
    } else {
      stdout.writeln('The overlay bundle is up to date.');
    }
    return;
  }

  final temp = Directory.systemTemp.createTempSync('jaspr_anatomy_overlay');
  try {
    final compiled = '${temp.path}/overlay.js';
    final result = await Process.run(Platform.resolvedExecutable, [
      'compile',
      'js',
      '-O2',
      '--no-source-maps',
      '-o',
      compiled,
      _entry,
    ]);
    if (result.exitCode != 0) {
      stderr
        ..writeln(result.stdout)
        ..writeln(result.stderr);
      exitCode = result.exitCode;
      return;
    }
    final script = _inlineSafe(File(compiled).readAsStringSync());
    File(_output).writeAsStringSync('''
// GENERATED by tool/build_overlay.dart. Do not edit by hand.
// ignore_for_file: type=lint

/// Hash of the overlay sources this bundle was built from.
const String overlayBundleHash = '$hash';

/// The overlay program, compiled to JavaScript and made safe to inline in a
/// `<script>` element.
const String overlayBundle = ${_dartLiteral(script)};
''');
    await Process.run(Platform.resolvedExecutable, ['format', _output]);
    stdout.writeln('Wrote $_output (${(script.length / 1024).round()} KB of JavaScript).');
  } finally {
    temp.deleteSync(recursive: true);
  }
}

/// Makes [script] safe inside a `<script>` element in a page of any encoding:
/// nothing the HTML parser could read as markup, and ASCII only.
String _inlineSafe(String script) {
  final backslash = String.fromCharCode(0x5c);
  final buffer = StringBuffer();
  final text = script
      .replaceAll(RegExp('</script', caseSensitive: false), '<$backslash/script')
      .replaceAll('<!--', '<$backslash!--');
  for (final unit in text.codeUnits) {
    if (unit < 0x80) {
      buffer.writeCharCode(unit);
    } else {
      // Outside ASCII only inside string literals, where an escape means the same.
      buffer.write('${backslash}u${unit.toRadixString(16).padLeft(4, '0')}');
    }
  }
  return buffer.toString().trim();
}

/// A Dart string literal with the value [text].
String _dartLiteral(String text) => jsonEncode(text).replaceAll(r'$', r'\$');

/// A hash of everything the bundle is compiled from.
String _hashSources() {
  final files = <File>[];
  for (final path in _sources) {
    if (FileSystemEntity.isDirectorySync(path)) {
      files.addAll(
        Directory(path).listSync(recursive: true).whereType<File>().where((file) => file.path.endsWith('.dart')),
      );
    } else {
      files.add(File(path));
    }
  }
  files.sort((a, b) => a.path.compareTo(b.path));
  // FNV-1a over 32 bits, twice with different seeds: no dependency needed
  // and plenty for telling "changed" from "unchanged".
  var first = 0x811c9dc5;
  var second = 0x01000193;
  for (final file in files) {
    for (final byte in utf8.encode('${file.path}\n${file.readAsStringSync()}')) {
      first = ((first ^ byte) * 0x01000193) & 0xffffffff;
      second = ((second ^ byte) * 0x811c9dc5) & 0xffffffff;
    }
  }
  return first.toRadixString(16).padLeft(8, '0') + second.toRadixString(16).padLeft(8, '0');
}
